// ¿Qué? Palabras de enlace en español que van en minúscula salvo que abran el nombre.
// ¿Para qué? "Perro de Pastor Belga" se lee mejor que "Perro De Pastor Belga".
const LOWERCASE_CONNECTORS = new Set(['de', 'del', 'la', 'las', 'los', 'y', 'en', 'a']);

// ¿Qué? Capitaliza la primera letra de cada "palabra" y de cada sub-segmento tras un
//   separador interno (guion, punto, paréntesis) — cubre casos como "Pas-Sarplaninac"
//   o "St. Bernhardshund" sin necesitar reglas especiales por raza.
function capitalizeSegments(word: string): string {
  return word.replace(/(^|[-.(])(\p{L})/gu, (_match, sep: string, letter: string) => sep + letter.toUpperCase());
}

// ¿Qué? Convierte el nombre oficial (en mayúsculas) al formato de visualización.
// ¿Para qué? Es la única función que decide capitalización — así todas las razas se ven
//   consistentes sin importar cómo las haya escrito la FCI en su página.
function toTitleCase(raw: string): string {
  return raw
    .toLowerCase()
    .split(' ')
    .map((word, index) => (index > 0 && LOWERCASE_CONNECTORS.has(word) ? word : capitalizeSegments(word)))
    .join(' ');
}

// ¿Qué? Catálogo final, ordenado alfabéticamente en español (ignora mayúsculas/acentos).
// ¿Impacto? Es lo único que importa `BreedCombobox.tsx` — un array de strings ya listo
//   para mostrar y filtrar, sin lógica de formateo fuera de este archivo.
export const DOG_BREEDS: string[] = RAW_BREEDS.map(toTitleCase).sort((a, b) => a.localeCompare(b, 'es'));
